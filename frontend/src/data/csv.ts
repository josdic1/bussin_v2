// Reads a CSV file the way Excel, Numbers and Google Sheets write it:
// commas, double-quoted cells, "" for a quote inside a cell, line breaks inside
// quoted cells, CRLF or LF line endings, and an optional UTF-8 BOM at the start.
export function parseCsv(input: string): string[][] {
  const text = input.replace(/^﻿/, "");
  const rows: string[][] = [];
  let row: string[] = [];
  let cell = "";
  let quoted = false;

  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') { cell += '"'; i += 1; } else quoted = false;
      } else cell += ch;
      continue;
    }
    if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(cell); cell = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i += 1;
      row.push(cell); rows.push(row); row = []; cell = "";
    } else cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  // Drop fully empty lines (Excel often adds them at the end).
  return rows.filter((r) => r.some((c) => c.trim() !== ""));
}
